"""Export reproducible contract interfaces and baseline storage layouts after forge build."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--artifacts", choices=["out", "out-batch"], default="out")
args = parser.parse_args()
parts = ["// Generated by scripts/boosters/export-abi.py. Do not edit by hand.\n"]
for contract, name in [("PackRegistry", "packRegistryAbi"), ("BoosterPacks", "boosterPacksAbi"), ("YunipalMonsters", "yunipalMonstersAbi")]:
    artifact = json.loads((root / "contracts/boosters" / args.artifacts / f"{contract}.sol" / f"{contract}.json").read_text())
    abi = [item for item in artifact["abi"] if item["type"] in ["event", "function", "error"]]
    parts.append(f"export const {name} = " + json.dumps(abi, separators=(",", ":")) + " as const;\n")
(root / "packages/yunipals-market-core/src/boosterAbi.ts").write_text("\n".join(parts))
