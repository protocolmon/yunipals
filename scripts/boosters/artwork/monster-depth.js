function setMonsterDepth(card, candidate, image) {
  const stage = Object.values(candidate.stages).find((result) => result.path === image);
  const path = candidate.traits.glitter === "Yes" ? ART_MONSTER_SILHOUETTES[stage?.sha256] : null;
  card.classList.toggle("has-monster-depth", Boolean(path));
  const foreground = card.querySelector(".monster-depth");
  const print = foreground.querySelector("img");
  foreground.hidden = !path;
  print.removeAttribute("src");
  card.style.removeProperty("--monster-mask");
  card.style.removeProperty("--background-mask");
  if (!path) return;
  const svg = (shape) => `url("data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1536">${shape}</svg>`)}")`;
  const shapes = (fill) => path.split(/(?=M)/).map((part) => part.trim()).filter(Boolean).map((part) => `<path d="${part}" fill="${fill}"/>`).join("");
  card.style.setProperty("--monster-mask", svg(shapes("white")));
  // A luminance mask unions overlapping subject parts such as wings/flippers.
  card.style.setProperty("--background-mask", svg(`<defs><mask id="background" mask-type="luminance"><rect width="1024" height="1536" fill="white"/>${shapes("black")}</mask></defs><rect width="1024" height="1536" fill="white" mask="url(#background)"/>`));
  print.src = image;
}

