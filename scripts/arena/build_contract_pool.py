#!/usr/bin/env python3
"""Generate the immutable onchain pool from the already published reveal, not a new draw."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
assignments = json.loads((ROOT / "docs/islands/arena-reveal-results-v1/assignments.json").read_text())["assignments"]
entries = [dict(tokenId=e["tokenId"], edition=e["edition"],
                weight=3 if e["edition"] == "Genesis" else 1,
                profileSha256=e["profileSha256"])
           for e in sorted(assignments, key=lambda a: int(a["tokenId"]))]
assert len(entries) == len({e['tokenId'] for e in entries}) == 898
assert [e['edition'] for e in entries] == ['Genesis'] * 525 + ['Personal'] * 373
pool = dict(chainId=8453, contract="0x79b68a12a2952a9a8d0cc4d0b3fb00252c41d168", entries=entries)
canonical = json.dumps(pool, sort_keys=True, separators=(',', ':'))
digest = hashlib.sha256(canonical.encode()).hexdigest()
packed = b''.join(int(e['tokenId']).to_bytes(2, 'big') for e in entries).hex()
source = f'''// SPDX-License-Identifier: MIT
pragma solidity 0.8.30;

// GENERATED by scripts/arena/build_contract_pool.py from the published reveal.
library IslandPool {{
    uint256 internal constant COUNT = 898;
    uint256 internal constant TOTAL_WEIGHT = 1948;
    bytes32 internal constant SHA256 = hex"{digest}";
    bytes internal constant IDS =
        hex"{packed}";

    function islandForTicket(uint256 ticket) internal pure returns (uint16) {{
        require(ticket < TOTAL_WEIGHT, "Ticket out of range");
        uint256 index = ticket < 1575 ? ticket / 3 : 525 + ticket - 1575;
        bytes memory ids = IDS;
        return (uint16(uint8(ids[index * 2])) << 8) | uint16(uint8(ids[index * 2 + 1]));
    }}
}}
'''
dest = ROOT / 'contracts/arena/src'
dest.mkdir(parents=True, exist_ok=True)
(dest / 'IslandPool.sol').write_text(source)
config = ROOT / 'contracts/arena/config'
config.mkdir(parents=True, exist_ok=True)
(config / 'island-pool.json').write_text(json.dumps(dict(sha256=digest, **pool), indent=2) + '\n')
print('898 islands / 1948 tickets / pool SHA-256:', digest)
